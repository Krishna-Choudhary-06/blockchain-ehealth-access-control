// ─────────────────────────────────────────────────────────────
// revokeAccess — NEW: remove a user from broadcast header
// Does NOT re-encrypt the file (that's the whole point)
// ─────────────────────────────────────────────────────────────
async function revokeAccess(dataId, revokedUserId) {
    const { contract, gateway } = await getContract();
    try {
        // Step 1: Get current data record to read existing header
        const dataResult = await contract.evaluateTransaction(
            'DataStorage:getDataRecord',
            dataId
        );
        const dataRecord = JSON.parse(dataResult.toString());

        // Step 2: Remove user from header using broadcastService
        const updatedHeader = broadcastService.revokeUserFromHeader(
            dataRecord.broadcastHeader || {},
            revokedUserId
        );

        // Step 3: Write updated header back to blockchain
        const result = await contract.submitTransaction(
            'DataStorage:updateBroadcastHeader',
            dataId,
            JSON.stringify(updatedHeader),
            `revoke:${revokedUserId}`
        );

        return JSON.parse(result.toString());
    } finally {
        gateway.disconnect();
    }
}

// ─────────────────────────────────────────────────────────────
// addAuthorizedUser — NEW: add a user to existing broadcast header
// Requires: the AES key K must be provided (by patient who knows it)
// In production: patient decrypts their own entry to get K, then re-encrypts for new user
//
// NOTE: For simplicity here, the patient must provide aesKeyHex
//       In a fully client-side implementation, this would happen in the browser
// ─────────────────────────────────────────────────────────────
async function addAuthorizedUser(dataId, newUserId, newUserPublicKey, aesKeyHex) {
    const { contract, gateway } = await getContract();
    try {
        // Step 1: Get current data record
        const dataResult = await contract.evaluateTransaction(
            'DataStorage:getDataRecord',
            dataId
        );
        const dataRecord = JSON.parse(dataResult.toString());

        // Step 2: Add new user to header
        const aesKeyBuffer = Buffer.from(aesKeyHex, 'hex');
        const updatedHeader = broadcastService.addUserToHeader(
            dataRecord.broadcastHeader || {},
            newUserId,
            newUserPublicKey,
            aesKeyBuffer
        );

        // Step 3: Write updated header back to blockchain
        const result = await contract.submitTransaction(
            'DataStorage:updateBroadcastHeader',
            dataId,
            JSON.stringify(updatedHeader),
            `add:${newUserId}`
        );

        return JSON.parse(result.toString());
    } finally {
        gateway.disconnect();
    }
}

