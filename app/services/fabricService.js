const { Gateway, Wallets } = require('fabric-network');
const path = require('path');
const fs = require('fs');
const broadcastService = require('./broadcastService');

// Path to the connection profile generated by fabric-samples
const ccpPath = path.resolve(
    process.env.HOME,
    'fabric-samples', 'test-network', 'organizations',
    'peerOrganizations', 'org1.example.com',
    'connection-org1.json'
);

// Path to the wallet holding enrolled identities
const walletPath = path.join(process.cwd(), 'wallet');

// ─────────────────────────────────────────────────────────────
// getContract — internal helper
// Opens Gateway → Channel → Contract
// Always call gateway.disconnect() in finally block
// ─────────────────────────────────────────────────────────────
async function getContract() {
    if (!fs.existsSync(ccpPath)) {
        throw new Error(
            `Connection profile not found at ${ccpPath}.\n` +
            `Run: cd ~/fabric-samples/test-network/organizations && ./ccp-generate.sh`
        );
    }

    const ccp = JSON.parse(fs.readFileSync(ccpPath, 'utf8'));
    const wallet = await Wallets.newFileSystemWallet(walletPath);

    const identity = await wallet.get('appUser');
    if (!identity) {
        throw new Error(
            'appUser identity not found in wallet.\n' +
            'Run: cd app && node enrollAdmin.js'
        );
    }

    const gateway = new Gateway();
    await gateway.connect(ccp, {
        wallet,
        identity: 'appUser',
        discovery: { enabled: true, asLocalhost: true }
    });

    const network = await gateway.getNetwork('healthchannel');
    const contract = network.getContract('healthcontract');

    return { contract, gateway };
}

// ─────────────────────────────────────────────────────────────
// registerUser — Algorithm 1: register a user on blockchain
// ─────────────────────────────────────────────────────────────
async function registerUser(userId, publicKey, role) {
    const { contract, gateway } = await getContract();
    try {
        const result = await contract.submitTransaction(
            'UserRegistry:registerUser',
            userId, publicKey, role
        );
        return JSON.parse(result.toString());
    } finally {
        gateway.disconnect();
    }
}

